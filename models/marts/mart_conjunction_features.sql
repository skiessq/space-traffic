    chaser_radial_pos_std_dev_meters,
    chaser_transverse_pos_std_dev_meters,
    chaser_normal_pos_std_dev_meters,
    chaser_radial_vel_std_dev_mps,
    case when chaser_radial_vel_std_dev_mps is not null then 1 else 0 end as has_chaser_velocity_covariance,
    chaser_transverse_vel_std_dev_mps,
    chaser_normal_vel_std_dev_mps,
    chaser_corr_transverse_pos_radial_pos,
    chaser_corr_normal_pos_radial_pos,
