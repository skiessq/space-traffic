    dataset_split,
    chaser_object_type,
    case when chaser_object_type = 'DEBRIS' then 1 else 0 end as is_chaser_debris,
    case when chaser_object_type = 'PAYLOAD' then 1 else 0 end as is_chaser_payload,
    case when chaser_object_type = 'UNKNOWN' then 1 else 0 end as is_chaser_unknown,
    risk,
    case when risk > -4.0 then 1 else 0 end as is_current_critical_risk,
    max_risk_estimate,
    max_risk_scaling,
    time_to_tca_days,
    miss_distance,
    mahalanobis_distance,
    log10(greatest(mahalanobis_distance, 1e-11)) as log_mahalanobis,
    relative_speed,
    relative_position_radial_meters,
    relative_position_transverse_meters,
    relative_position_normal_meters,
    relative_velocity_radial_mps,
    relative_velocity_transverse_mps,
    relative_velocity_normal_mps,
    geocentric_latitude_degrees,
    relative_velocity_azimuth_degrees,
    relative_velocity_elevation_degrees,
