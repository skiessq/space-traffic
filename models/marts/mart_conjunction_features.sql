    target_residuals_accepted_ratio,
    target_days_to_last_ob_start,
    target_days_to_last_ob_end,
    target_od_weighted_rms,
    chaser_collision_span_meters,
    chaser_apogee_altitude_km,
    chaser_perigee_altitude_km,
    chaser_j2000_semi_major_axis_km,
    chaser_j2000_eccentricity,
